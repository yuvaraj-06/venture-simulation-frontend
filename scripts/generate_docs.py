import os
#!/usr/bin/env python3
"""Generate relevant documents for all venture simulations and upload to S3."""
import json, boto3, time
from datetime import datetime, timezone
from pymongo import MongoClient

MONGO_URI = os.environ.get("MONGODB_URI", "")
S3_BUCKET = "shareosimages"
S3_PREFIX = "polsia/documents"
AWS_KEY = os.environ.get("AWS_ACCESS_KEY_ID", "")
AWS_SECRET = os.environ.get("AWS_SECRET_ACCESS_KEY", "")

s3 = boto3.client('s3', aws_access_key_id=AWS_KEY, aws_secret_access_key=AWS_SECRET, region_name='us-west-2')
client = MongoClient(MONGO_URI)
db = client.get_database('shareos')

def upload_md(venture_id, filename, content):
    key = f"{S3_PREFIX}/{venture_id}/{filename}"
    s3.put_object(Bucket=S3_BUCKET, Key=key, Body=content.encode(), ContentType='text/markdown')
    url = f"https://{S3_BUCKET}.s3.us-west-2.amazonaws.com/{key}"
    return url

def generate_pitch_deck(v):
    meta = v.get('simulation_metadata', {})
    summary = v.get('executive_summary', {})
    products = v.get('products', [])
    team = v.get('founding_team', [])
    signal = v.get('signal_origin', {})
    stages = v.get('stages', [])
    analysis = v.get('analysis', {})
    name = meta.get('venture_name', v['cmny_id'])
    vertical = meta.get('vertical', '')
    subdomain = meta.get('subdomain', '')
    tam = meta.get('tam_formatted', meta.get('tam', ''))
    target_val = summary.get('target_valuation', 0)
    current_val = summary.get('current_valuation', 0)
    takeaways = summary.get('key_takeaways', [])

    product_rows = ""
    for p in products[:5]:
        pname = p.get('name', 'Product')
        cat = p.get('category', '')
        diff = p.get('differentiator', '')
        pricing = p.get('pricing', '')
        product_rows += f"| {pname} | {cat} | {pricing} | {diff[:80]} |\n"

    team_rows = ""
    for t in team[:5]:
        tname = t.get('name', '')
        role = t.get('role', '')
        expertise = ', '.join(t.get('expertise', [])[:3]) if isinstance(t.get('expertise'), list) else str(t.get('expertise', ''))[:60]
        team_rows += f"| {tname} | {role} | {expertise} |\n"

    signals = signal.get('detection_signals', [])
    signal_items = "\n".join([f"- {s.get('signal', s) if isinstance(s, dict) else s}" for s in signals[:6]])

    stage_rows = ""
    for st in stages[:3]:
        sname = st.get('stage_name', '')
        dur = st.get('duration', '')
        ss = st.get('stage_summary', {})
        perf = ss.get('performance_score', '--')
        exe = ss.get('execution_score', '--')
        acost = ss.get('total_agent_cost', '--')
        stage_rows += f"| {sname} | {dur} | {perf} | {exe} | ${acost} |\n"

    return f"""# {name} - Investor Pitch Deck

## The Opportunity

**{subdomain}**

| Metric | Value |
|--------|-------|
| Vertical | {vertical} |
| TAM | {tam} |
| Target Valuation | ${target_val:,.0f} |
| Current Valuation | ${current_val:,.0f} |

## Executive Summary

{chr(10).join([f'- {t}' for t in takeaways[:5]])}

## Signal Origin

**Signal Strength:** {signal.get('signal_strength', '--') if isinstance(signal.get('signal_strength'), (int, float)) else signal.get('signal_strength', {}).get('score', '--')}/100

**Core Thesis:**
{signal.get('core_thesis', 'N/A')}

### Detection Signals
{signal_items}

## Products & Services

| Product | Category | Pricing | Differentiator |
|---------|----------|---------|----------------|
{product_rows}

## Founding Team

| Name | Role | Expertise |
|------|------|-----------|
{team_rows}

## Stage Progression

| Stage | Duration | Performance | Execution | Agent Cost |
|-------|----------|-------------|-----------|------------|
{stage_rows}

## Why Now

The convergence of {vertical.lower()} technology advances, growing market demand ({tam} TAM), and ShareOS's autonomous venture creation infrastructure creates a unique window to build {name} at a fraction of traditional cost.

## The Ask

Seeking seed investment to advance from Generate to Validate stage, targeting first revenue within 90 days.

---
*Generated by ShareOS Autonomous Venture System*
*{datetime.now(timezone.utc).strftime('%B %d, %Y')}*
"""


