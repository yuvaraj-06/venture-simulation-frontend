{chr(10).join([f'### {i+1}. {s.get("signal", s) if isinstance(s, dict) else s}' + (chr(10) + f'*{s.get("detail", "")}*' if isinstance(s, dict) and s.get("detail") else '') for i, s in enumerate(signals[:8])])}

